const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const tools = require('./project-tools');
test('import preserves supporting files, refuses overwrite and rejects invalid skills', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ai-terminal-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const source = path.join(root, 'source'), target = path.join(root, 'project', '.agents', 'skills');
  await fs.mkdir(path.join(source, 'references'), { recursive: true });
  await fs.writeFile(path.join(source, 'SKILL.md'), '---\nname: sample-check\ndescription: A test fixture\n---\nFixture instructions.');
  await fs.writeFile(path.join(source, 'references', 'note.md'), 'support');
  const result = await tools.importSkill(source, target);
  assert.equal(result.files, 2);
  assert.equal(await fs.readFile(path.join(result.destination, 'references', 'note.md'), 'utf8'), 'support');
  await assert.rejects(tools.importSkill(source, target), /Ya existe/);
  const listing = await tools.listSkills(path.join(root, 'project'));
  assert(listing.skills.some(s => s.name === 'sample-check' && s.scope === 'Proyecto' && s.agent === 'Codex'));
  await fs.writeFile(path.join(source, 'SKILL.md'), '---\nname: ../../escape\ndescription: invalid\n---\n');
  await assert.rejects(tools.importSkill(source, target), /cabecera YAML/);
  await assert.rejects(tools.projectPath(path.join(root, 'project'), '..'), /fuera/);
});
test('Git panel returns staged and unstaged diffs and new files', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ai-terminal-git-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const git = args => execFileSync('git', args, { cwd: root, windowsHide: true, stdio: 'pipe' });
  git(['init']);
  await fs.writeFile(path.join(root, 'sample.txt'), 'staged line\n'); git(['add', 'sample.txt']);
  await fs.writeFile(path.join(root, 'sample.txt'), 'changed line\n');
  await fs.writeFile(path.join(root, 'new.txt'), 'new file\n');
  const result = await tools.changes(root);
  assert.match(result.status, /new.txt/); assert(result.entries.some(e => e.relative === 'sample.txt' && e.state === 'AM'));
  const entries = await tools.files(root, ''); assert(entries.some(e => e.name === 'sample.txt')); assert(!entries.some(e => e.name === '.git'));
  const change = await tools.fileChange(root, 'sample.txt');
  assert.match(change.working, /\+changed line/); assert.match(change.staged, /\+staged line/); assert.equal(change.content, 'changed line\n');
  assert.equal((await tools.fileChange(root, 'new.txt')).content, 'new file\n');
  await assert.rejects(tools.fileChange(root, '../outside'), /fuera/);
  await fs.writeFile(path.join(root, '[literal] á.txt'), 'literal filename\n');
  git(['add', '[literal] á.txt']);
  await fs.writeFile(path.join(root, '[literal] á.txt'), 'changed literal filename\n');
  assert.match((await tools.fileChange(root, '[literal] á.txt')).working, /\+changed literal filename/);
  await fs.unlink(path.join(root, 'sample.txt'));
  const deleted = await tools.fileChange(root, 'sample.txt');
  assert.match(deleted.working, /-staged line/); assert.match(deleted.readError, /eliminado/);
});
test('skill previews do not write, detect duplicates, and catch changed import sources', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ai-terminal-preview-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const fields = { name: 'fixture-preview', description: 'When testing: "quotes" and accents á', instructions: 'Test instructions.\nSecond line.' };
  const destination = path.join(root, 'destination');
  const preview = await tools.previewCreatedSkill(destination, fields);
  await assert.rejects(fs.access(preview.destination));
  assert.match(preview.content, /name: fixture-preview/);
  const created = await tools.createSkill(destination, fields);
  assert.equal(tools.metadata(await tools.textFile(path.join(created.destination, 'SKILL.md'))).name, fields.name);
  assert.equal((await tools.previewCreatedSkill(destination, fields)).exists, true);
  await assert.rejects(tools.createSkill(destination, fields), /Ya existe/);
  const importRoot = path.join(root, 'imported');
  const importedPreview = await tools.inspectSkill(created.destination, importRoot);
  await assert.rejects(fs.access(importedPreview.destination));
  await fs.appendFile(path.join(created.destination, 'SKILL.md'), '\nChanged.');
  await assert.rejects(tools.importSkill(created.destination, importRoot, importedPreview.fingerprint), /ha cambiado/);
  await assert.rejects(tools.previewCreatedSkill(destination, { ...fields, name: '../escape' }), /Nombre/);
});
