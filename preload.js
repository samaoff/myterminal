const { contextBridge, ipcRenderer } = require('electron');
const initialPreferences = ipcRenderer.sendSync('preferences-read');
contextBridge.exposeInMainWorld('desktop', {
  initialPreferences,
  notifyTask: (id, name, message) => ipcRenderer.invoke('task-notify', { id, name, message }),
  onTaskNoticeOpen: callback => ipcRenderer.on('task-notice-open', (_event, id) => callback(id)),
  sftpOpen: (id, credentials, folder) => ipcRenderer.invoke('sftp-open', { profileId: initialPreferences.profileId, id, credentials, folder }),
  sftpList: (id, side, target) => ipcRenderer.invoke('sftp-list', { id, side, target }),
  sftpTransfer: (id, direction, name) => ipcRenderer.invoke('sftp-transfer', { id, direction, name }),
  sftpCancel: id => ipcRenderer.invoke('sftp-cancel', id),
  sftpClose: id => ipcRenderer.invoke('sftp-close', id),
  onSftpProgress: callback => ipcRenderer.on('sftp-progress', (_event, value) => callback(value)),
  onSftpClosed: callback => ipcRenderer.on('sftp-closed', (_event, id) => callback(id)),
  detectedShells: () => ipcRenderer.invoke('detected-shells'),
  externalState: () => ipcRenderer.invoke('external-state'),
  externalEnter: displayId => ipcRenderer.invoke('external-enter', displayId),
  externalExit: () => ipcRenderer.invoke('external-exit'),
  externalLaunch: () => ipcRenderer.invoke('external-launch'),
  externalPick: () => ipcRenderer.invoke('external-pick'),
  onExternalMode: callback => ipcRenderer.on('external-mode', (_event, state) => callback(state)),
  openDisplaySettings: () => ipcRenderer.invoke('ss-display-settings'),
  secondScreen: {
    state: () => ipcRenderer.invoke('ss-state'),
    sources: () => ipcRenderer.invoke('ss-sources'),
    start: id => ipcRenderer.invoke('ss-start', id),
    stop: () => ipcRenderer.invoke('ss-stop'),
    fit: value => ipcRenderer.invoke('ss-fit', value),
    pause: value => ipcRenderer.invoke('ss-pause', value),
    autoFit: value => ipcRenderer.invoke('ss-auto-fit', value),
    resolution: (width, height) => ipcRenderer.invoke('ss-resolution', { width, height }),
    fitDevice: () => ipcRenderer.invoke('ss-fit-device'),
    driverStatus: () => ipcRenderer.invoke('ss-driver-status'),
    driverInstall: () => ipcRenderer.invoke('ss-driver-install'),
    driverUninstall: () => ipcRenderer.invoke('ss-driver-uninstall'),
    onEvent: callback => ipcRenderer.on('ss-event', (_event, state) => callback(state))
  },
  setTitleBar: colors => ipcRenderer.invoke('titlebar-set', colors),
  savePreferences: patch => ipcRenderer.invoke('preferences-save', { profileId: initialPreferences.profileId, patch }),
  userProfiles: () => ipcRenderer.invoke('user-profiles-list'),
  createUserProfile: name => ipcRenderer.invoke('user-profile-create', name),
  renameUserProfile: (id, name) => ipcRenderer.invoke('user-profile-rename', {id, name}),
  switchUserProfile: id => ipcRenderer.invoke('user-profile-switch', id),
  rememberProject: folder => ipcRenderer.invoke('project-remember', {profileId: initialPreferences.profileId, folder}),
  remoteConnections: () => ipcRenderer.invoke('remote-connections-list'),
  saveConnection: connection => ipcRenderer.invoke('remote-connection-save', {profileId: initialPreferences.profileId, connection}),
  removeConnection: id => ipcRenderer.invoke('remote-connection-remove', {profileId: initialPreferences.profileId, id}),
  remoteClients: () => ipcRenderer.invoke('remote-clients'),
  pickRemotePath: kind => ipcRenderer.invoke('remote-pick-path', {profileId: initialPreferences.profileId, kind}),
  openRemoteDesktop: id => ipcRenderer.invoke('remote-desktop-open', {profileId: initialPreferences.profileId,id}),
  layoutRemoteDesktop: (id,bounds) => ipcRenderer.send('remote-desktop-layout',{id,bounds}),
  disconnectRemoteDesktop: id => ipcRenderer.send('remote-desktop-disconnect',id),
  onRemoteDesktopStatus: callback => ipcRenderer.on('rdp-status',(_event,message)=>callback(message)),
  onRemoteDesktopLayout: callback => ipcRenderer.on('rdp-layout-request',()=>callback()),
  terminalProfiles: () => ipcRenderer.invoke('terminal-profiles-list'),
  saveTerminal: profile => ipcRenderer.invoke('terminal-profile-save', profile),
  removeTerminal: id => ipcRenderer.invoke('terminal-profile-remove', id),
  appInfo: () => ipcRenderer.invoke('app-info'),
  updateState: () => ipcRenderer.invoke('app-update-state'),
  checkUpdates: () => ipcRenderer.invoke('app-update-check'),
  updateSettings: options => ipcRenderer.invoke('app-update-settings', options),
  downloadUpdate: () => ipcRenderer.invoke('app-update-download'),
  cancelUpdate: () => ipcRenderer.invoke('app-update-cancel'),
  installUpdate: () => ipcRenderer.invoke('app-update-install'),
  updateReleases: () => ipcRenderer.invoke('app-update-releases'),
  onUpdateState: callback => ipcRenderer.on('app-update-state', (_event, state) => callback(state)),
  openCreatorWebsite: () => ipcRenderer.invoke('open-creator-website'),
  usage: (id, force = false) => ipcRenderer.invoke('ai-usage', {id,force}),
  openProject: folder => ipcRenderer.invoke('project-open', folder),
  deleteSkill: (folder,file) => ipcRenderer.invoke('skill-delete',{folder,file}),
  gitInfo: folder => ipcRenderer.invoke('git-info',folder),
  gitAction: (folder,action,relative,message) => ipcRenderer.invoke('git-action',{folder,action,relative,message}),
  skills: folder => ipcRenderer.invoke('skills-list', folder),
  readSkill: file => ipcRenderer.invoke('skill-read', file),
  previewImport: options => ipcRenderer.invoke('skill-preview-import', options),
  previewCreate: options => ipcRenderer.invoke('skill-preview-create', options),
  commitSkill: token => ipcRenderer.invoke('skill-commit', token),
  fileChange: (folder, relative) => ipcRenderer.invoke('project-file-change', { folder, relative }),
  files: (folder, relative = '') => ipcRenderer.invoke('project-files', { folder, relative }),
  readFile: (folder, relative) => ipcRenderer.invoke('project-read', { folder, relative }),
  changes: folder => ipcRenderer.invoke('project-changes', folder),
  projects: () => ipcRenderer.invoke('projects'),
  forgetProject: folder => ipcRenderer.invoke('project-forget', folder),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  create: options => ipcRenderer.invoke('create-terminal', {...options, profileId:initialPreferences.profileId}),
  write: (id, data) => ipcRenderer.send('terminal-write', { id, data }),
  consumed: (id, length) => ipcRenderer.send('terminal-consumed', { id, length }),
  resize: (id, cols, rows) => ipcRenderer.send('terminal-resize', { id, cols, rows }),
  close: id => ipcRenderer.invoke('terminal-close', id),
  onData: callback => ipcRenderer.on('terminal-data', (_event, payload) => callback(payload)),
  onExit: callback => ipcRenderer.on('terminal-exit', (_event, payload) => callback(payload))
});
